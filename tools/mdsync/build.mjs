import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(here, '../..');
const upstream = path.resolve(process.argv[2] ?? path.join(project, '../mdsync-validation'));
const pin = '6f0190efd517b709ff21c4d77bcc0b221bce52b6';
assert.equal(spawnSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).stdout.trim(), pin);
assert.equal(spawnSync('git', ['status', '--porcelain', '--untracked-files=no'], { cwd: upstream, encoding: 'utf8' }).stdout.trim(), '');
const require = createRequire(path.join(upstream, 'packages/plugin/package.json'));
const { build } = require('esbuild');
const output = path.join(project, 'src/vendor/mdsync');
await mkdir(output, { recursive: true });
const result = await build({
  entryPoints: [path.join(here, 'entry.ts')], bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  outfile: path.join(output, 'core.js'), minify: true, metafile: true, legalComments: 'eof',
  alias: { '@': path.join(upstream, 'packages/plugin/src'), obsidian: path.join(here, 'host.ts'),
    '@mdsync/protocol': path.join(upstream, 'packages/protocol/src/index.ts') },
  plugins: [{ name: 'atomic-s3-manifest', setup(build) {
    build.onLoad({ filter: /sync\/remote\/manifest\.ts$/ }, async ({ path: file }) => {
      const source = await readFile(file, 'utf8');
      const old = 'await storage.put(REMOTE_MANIFEST_KEY, blob, "application/octet-stream");';
      assert.equal(source.split(old).length, 2);
      const patch = `const validator = validators.get(storage);
        const etag = fetched ? validator?.etag : null;
        if (fetched && (!etag || validator?.manifest.snapshotId !== fetched.snapshotId)) {
          throw new Error("S3 did not provide a fresh manifest ETag; refusing an unconditional update");
        }
        if (!storage.putManifest) throw new Error("Atomic manifest writes are required");
        if (!await storage.putManifest(blob, etag)) throw new ConcurrentPushError("Concurrent manifest update");`;
      return { contents: source.replace(old, patch), loader: 'ts' };
    });
  } }],
});
await writeFile(path.join(output, 'LICENSE'), await readFile(path.join(upstream, 'LICENSE')));
await writeFile(path.join(output, 'NOTICE.md'), `# MDSync core\n\nUpstream: https://github.com/k1tbyte/mdsync\nCommit: ${pin} (1.5.1, MIT).\n\nGenerated by tools/mdsync/build.mjs. The manifest publisher is modified to require atomic ETag writes; Obsidian host calls use tools/mdsync/host.ts. Other algorithms are bundled from the pinned source.\n\nBundled third-party dependencies retain their legal comments in core.js. Input files are recorded in inputs.json.\n`);
await writeFile(path.join(output, 'inputs.json'), JSON.stringify({ commit: pin, inputs: Object.keys(result.metafile.inputs).sort() }, null, 2) + '\n');
const notices = [];
for (const name of ['@jest/diff-sequences', 'lz-string']) {
  const file = require.resolve(`${name}/package.json`);
  const pkg = JSON.parse(await readFile(file, 'utf8'));
  const license = await readFile(path.join(path.dirname(file), 'LICENSE'), 'utf8');
  notices.push(`${name} ${pkg.version}\n${license}`);
}
await writeFile(path.join(output, 'THIRD-PARTY-LICENSES.txt'), notices.join('\n\n'));
console.log(`MDSync core: ${result.metafile.outputs[path.relative(process.cwd(), path.join(output, 'core.js'))]?.bytes ?? 'generated'} bytes`);
